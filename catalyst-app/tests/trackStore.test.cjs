const assert = require('node:assert/strict')
const { test } = require('node:test')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')

// Track layouts live in the workspace database; YAML files only seed it.
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'catalyst-track-store-'))
process.env.CATALYST_INSTANCE_DIR = root
const { initSchema, withDb, releaseSharedInstance } = require('../dist-main/garmin/loadToDb.js')
const { DB_PATH, TRACKS_DIR } = require('../dist-main/garmin/paths.js')
const {
  customComplexNames, getTrackLayout, layoutComplexes, saveTrackComplexes, saveTrackCorners, seedTrackLayouts,
} = require('../dist-main/garmin/trackStore.js')
const { buildCoachPacket, renderPacket } = require('../dist-main/garmin/coachPacket.js')
const { readReviewDefinition } = require('../dist-main/garmin/reviewStore.js')

const VIR = 'Virginia International Raceway'
const corner = (turn, name, apex) => `  - turn: ${turn}\n    name: "${name}"\n    direction: left\n    apex_idx: ${apex}\n    dist_idx_start: ${apex - 20}\n    dist_idx_end: ${apex + 20}\n`

// The Grand course file as the old editor left it: corners corrected by the
// driver, but a complexes block frozen from the corners before the fix.
const GRAND_YAML = `# Auto-generated by detect_corners.py
track_name: ${VIR}
track_configuration_name: Grand West Course
mean_line_guid: grand-line
total_dist_m: 1000

segments:
  - id: 1
    start_dist_m: 0
    end_dist_m: 1000
    flag: 1

complexes:
  - id: C1
    name: "Start straight"
    start_m: 0
    end_m: 100
  - id: C2
    name: "C1–C2 · Corner 1 to Corner 2"
    start_m: 100
    end_m: 500
    corners: "C1,C2"
  - id: C3
    name: "Oak Tree complex"
    start_m: 500
    end_m: 1000
    corners: "C3"
# Named corners, in driving order.
corners:
${corner('T1', 'Horse Shoe', 200)}${corner('T2', 'NASCAR', 400)}${corner('T3', 'Oak Tree', 700)}`

// A layout the old editor created from scratch: no header at all.
const NORTH_YAML = `# Track configuration (created by Tracks editor)
corners:
${corner('N1', 'North One', 150)}`

async function addSession(con, guid, config, line, configurationId) {
  await con.run(`INSERT INTO sessions (session_guid, session_start, track_name, track_configuration_name,
    track_configuration_id, mean_line_guid, vehicle_guid, account, details_loaded)
    VALUES (?, '2026-10-30 14:00:00', ?, ?, ?, ?, 'car', 'driver', true)`, [guid, VIR, config, configurationId, line])
  for (const [lap, ms] of [[0, 60000], [1, 61000]]) {
    await con.run("INSERT INTO laps (session_guid, lap_index, lap_type, duration_ms, lap_descriptor) VALUES (?, ?, 'DRIVEN', ?, 0)", [guid, lap, ms])
    for (let d = 0; d <= 1000; d += 10) await con.run(
      'INSERT INTO samples (session_guid, lap_index, distance_m, time_ms, gnss_speed_mps) VALUES (?, ?, ?, ?, 30)', [guid, lap, d, d * ms / 1000])
  }
}

test('track layouts are seeded from YAML once, then owned by the database', async t => {
  t.after(() => { releaseSharedInstance(); fs.rmSync(root, { recursive: true, force: true }) })
  fs.mkdirSync(path.dirname(DB_PATH), { recursive: true })
  fs.mkdirSync(TRACKS_DIR, { recursive: true })
  const grandFile = path.join(TRACKS_DIR, 'vir-grand-west-course.yaml')
  const northFile = path.join(TRACKS_DIR, 'virginia-north-course.yaml')
  fs.writeFileSync(grandFile, GRAND_YAML)
  fs.writeFileSync(northFile, NORTH_YAML)
  const db = fn => withDb(fn, DB_PATH)
  await db(initSchema)
  await db(async con => {
    await addSession(con, 'grand', 'Grand West Course', 'grand-line', 99)
    await addSession(con, 'north', 'North Course', 'north-line', 98)
  })

  await t.test('the startup import brings in every layout, including header-less editor files', async () => {
    const imported = await db(con => seedTrackLayouts(con))
    assert.deepEqual(imported.sort(), ['grand-line', 'north-line'])
    assert.deepEqual(await db(con => seedTrackLayouts(con)), [], 'a second run imports nothing')
    assert.equal(fs.readFileSync(grandFile, 'utf8'), GRAND_YAML, 'seed files are never rewritten')
    const north = await db(con => getTrackLayout(con, 'north-line'))
    assert.deepEqual(north.corners.map(c => c.turn), ['N1'])
    assert.equal(north.configName, 'North Course')
  })

  await t.test('imported corners keep the driver edits; generated complex names follow them', async () => {
    const layout = await db(con => getTrackLayout(con, 'grand-line'))
    assert.deepEqual(layout.corners.map(c => [c.turn, c.name, c.apex_idx, c.dist_idx_start]), [
      ['T1', 'Horse Shoe', 200, 180], ['T2', 'NASCAR', 400, 380], ['T3', 'Oak Tree', 700, 680],
    ])
    assert.equal(layout.complexesOrigin, 'seed')
    assert.deepEqual(layout.complexes.map(c => c.name), [null, null, 'Oak Tree complex'])
    assert.deepEqual(layout.segments.map(s => [s.id, s.start_dist_m, s.end_dist_m]), [[1, 0, 1000]])
    assert.deepEqual(layoutComplexes(layout).map(c => [c.id, c.name, c.corners.join(',')]), [
      ['C1', 'Start straight', ''],
      ['C2', 'T1–T2 · Horse Shoe to NASCAR', 'T1,T2'],
      ['C3', 'Oak Tree complex', 'T3'],
    ])
  })

  await t.test('the coach packet and session review use the saved corners, before and after a rename', async () => {
    let packet = await db(con => buildCoachPacket(con, { sessionGuids: ['grand'], system: 'imperial' }))
    assert.equal(packet.complexSource, 'track')
    assert.equal(packet.complexes[1].name, 'T1–T2 · Horse Shoe to NASCAR')
    assert.doesNotMatch(renderPacket(packet), /Corner 1|C1–C2/)

    const layout = await db(con => getTrackLayout(con, 'grand-line'))
    const renamed = layout.corners.map(c => c.turn === 'T2' ? { ...c, turn: 'T2a', name: 'Climbing Esses' } : c)
    await db(con => saveTrackCorners(con, 'grand-line', { trackName: VIR, configName: 'Grand West Course', totalDistM: 1000, segments: [] }, renamed))

    packet = await db(con => buildCoachPacket(con, { sessionGuids: ['grand'], system: 'imperial' }))
    assert.equal(packet.complexes[1].name, 'T1–T2a · Horse Shoe to Climbing Esses')
    assert.deepEqual(packet.complexes[1].corners, ['T1', 'T2a'])
    assert.doesNotMatch(renderPacket(packet), /NASCAR/)
    const review = await db(con => readReviewDefinition(con, { mean_line_guid: 'grand-line' }))
    assert.deepEqual(review.regions.filter(r => r.kind === 'corner').map(r => r.name), ['T1 · Horse Shoe', 'T2a · Climbing Esses', 'T3 · Oak Tree'])
    assert.equal((await db(con => getTrackLayout(con, 'grand-line'))).complexes.length, 3, 'imported complexes keep their boundaries')
  })

  await t.test('editing a seed file after import changes nothing', async () => {
    fs.writeFileSync(grandFile, GRAND_YAML.replace('Horse Shoe', 'Stale Name'))
    assert.deepEqual(await db(con => seedTrackLayouts(con)), [])
    const layout = await db(con => getTrackLayout(con, 'grand-line'))
    assert.equal(layout.corners.find(c => c.turn === 'T1').name, 'Horse Shoe')
  })

  await t.test('derived complexes re-derive after a corner save; edited ones are kept', async () => {
    const layout = await db(con => getTrackLayout(con, 'grand-line'))
    const identity = { trackName: VIR, configName: 'Grand West Course', totalDistM: 1000, segments: [] }
    await db(con => saveTrackComplexes(con, 'grand-line', [{ startM: 0, endM: 500, name: null }, { startM: 500, endM: 1000, name: null }], 'derived'))
    await db(con => saveTrackCorners(con, 'grand-line', identity, layout.corners))
    let after = await db(con => getTrackLayout(con, 'grand-line'))
    assert.deepEqual(after.complexes, [])
    assert.equal(after.complexesOrigin, null)

    const ranges = [{ startM: 0, endM: 500, name: 'T1–T2a · Horse Shoe to Climbing Esses' }, { startM: 500, endM: 1000, name: 'Back half' }]
    const named = customComplexNames(layout.corners, ranges)
    assert.deepEqual(named.map(c => c.name), [null, 'Back half'], 'a default name is not stored as a custom one')
    await db(con => saveTrackComplexes(con, 'grand-line', named, 'edited'))
    await db(con => saveTrackCorners(con, 'grand-line', identity, layout.corners.map(c => c.turn === 'T1' ? { ...c, name: 'Horseshoe' } : c)))
    after = await db(con => getTrackLayout(con, 'grand-line'))
    assert.equal(after.complexesOrigin, 'edited')
    assert.deepEqual(layoutComplexes(after).map(c => c.name), ['T1–T2a · Horseshoe to Climbing Esses', 'Back half'])
  })

  await t.test('a seed added later is imported on first read; unknown layouts stay empty', async () => {
    fs.writeFileSync(path.join(TRACKS_DIR, 'late.yaml'), `track_name: ${VIR}\ntrack_configuration_name: Patriot Course\nmean_line_guid: late-line\ntotal_dist_m: 500\ncorners:\n${corner('P1', 'Patriot One', 100)}`)
    const late = await db(con => getTrackLayout(con, 'late-line'))
    assert.deepEqual(late.corners.map(c => c.turn), ['P1'])
    assert.equal(await db(con => getTrackLayout(con, 'missing-line')), null)
  })
})
